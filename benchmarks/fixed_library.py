"""Controlled derivative substitutions on identical points; no network training.

Legacy caches must be generated by intermediate/diag_library.py. They have no
time array, so time alignment is inferred from that script and explicitly recorded.
The FD reference is a numerical comparator, not exact derivatives.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from common import ROOT, TRUE_TERMS, environment, fingerprint, normalized_condition, relative_l2, subset, support_score
from deepgs.data import load_profile_txt
from deepgs.grouping import build_system
from deepgs.library import CandidateLibrary, finite_difference_library, term_names
from deepgs.physics import SOILS
from deepgs.sparse import aic_score, select_spline, sgtr_path
from deepgs.utils import save_json


def metrics(lib, fd):
    errors = {"theta": relative_l2(lib.theta, fd.theta), "theta_t": relative_l2(lib.theta_t, fd.theta_t)}
    errors.update({n: relative_l2(lib.terms[:, i], fd.terms[:, i]) for i, n in enumerate(lib.names)})
    columns = [lib.names.index(n) for n in TRUE_TERMS]
    with np.errstate(invalid="ignore", divide="ignore", over="ignore"):
        truth = SOILS["loam"].coefficients(lib.theta[:, 0])
    prediction = sum(truth[n] * lib.terms[:, lib.names.index(n)] for n in TRUE_TERMS)
    valid = np.isfinite(prediction)
    return dict(relative_to_fd=errors, true_structure_condition=normalized_condition(lib.terms[:, columns]),
                reference_points=dict(valid=int(valid.sum()), total=int(valid.size)),
                reference_pde_relative_residual=relative_l2(prediction[valid], lib.theta_t[valid, 0]) if valid.any() else None)


def selections(lib, sweep):
    lib3 = subset(lib, slice(None), term_names(3))
    out = []
    for mode in ("global", "group"):
        windows = (0.001, 0.005, 0.01) if sweep and mode == "group" else (0.001,)
        for win in windows:
            system = build_system(lib3, win, 200 if mode == "global" else 100,
                                  mode, by_depth=mode == "group", merge_tail=0.01)
            lam = 1e-4 if mode == "global" else 1e-2
            # epsilon does not change the threshold path; score each support afterwards.
            path = sgtr_path(system, num_tols=200, lam=lam, maxit=1, epsilon=0.01)
            energy = sum(float(np.sum(y**2)) for y in system.y)
            rules = [("epsilon", v) for v in ((0.01, 10**-1.5, 0.1) if mode == "global" else (10**1.2,))]
            if sweep and mode == "group":
                rules += [("energy_gain", v) for v in (0.02, 0.03, 0.04, 0.05, 0.08, 0.15)]
            for rule, value in rules:
                epsilon = value if rule == "epsilon" else value * energy / 2
                corrected = mode == "global"
                best = min(path, key=lambda p: aic_score(p["rss"], system.n_samples, p["k"], epsilon, corrected))
                names = [system.feature_names[j] for j in best["active"]]
                out.append(dict(selector="sgtr", normalization=mode, win_size=win, lam=lam, rule=rule,
                                value=value, epsilon=epsilon, corrected=corrected, groups=system.n_groups,
                                terms=names, rss=best["rss"], score=support_score(names),
                                path=[dict(terms=[system.feature_names[j] for j in p["active"]], rss=p["rss"],
                                           score=aic_score(p["rss"], system.n_samples, p["k"], epsilon, corrected)) for p in path]))
    system = build_system(lib, 0.001, 100, "global", merge_tail=0)
    for lam in (0.01, 0.001, 0.0001):
        result = select_spline(system, lam=lam)
        names = None if result is None else result.names
        out.append(dict(selector="spline", lam=lam, terms=names, groups=system.n_groups,
                        score=support_score(names), path=None if result is None else result.path))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", type=Path, default=ROOT / "intermediate/diag")
    parser.add_argument("--output", type=Path, default=ROOT / "intermediate/runs/fixed_library")
    parser.add_argument("--time-stride", type=int, default=1)
    parser.add_argument("--variants", nargs="+", default=["tanh_norm_lbfgs", "silu_norm_lbfgs", "sin_raw_adam"])
    parser.add_argument("--no-hybrids", action="store_true")
    args = parser.parse_args()
    if args.time_stride < 1:
        parser.error("time-stride must be positive")
    paths = [args.cache_dir / f"lib_{name}_noise0.0.npz" for name in args.variants]
    metadata_paths = [p.with_suffix(".json") for p in paths if p.with_suffix(".json").exists()]
    for path in metadata_paths:
        metadata = json.loads(path.read_text(encoding="utf-8"))
        settings = metadata["settings"]
        if metadata.get("status") != "completed" or settings["seed"] != 1 or settings["noise"] != 0:
            raise ValueError("This diagnostic expects completed clean seed-1 caches")
        if metadata["cache"]["sha256"] != fingerprint(path.with_suffix(".npz"))["sha256"]:
            raise ValueError("Cache hash differs from its metadata")
    full = load_profile_txt(ROOT / "intermediate/data/th.txt")
    window = full.select_depths(full.depths[3:28])
    fd = finite_difference_library(window.theta.T, window.depths, window.times, 4)
    rows = np.arange(len(fd.theta)).reshape(21, -1)[:, ::args.time_stride].ravel()
    fd = subset(fd, rows)
    args.output.mkdir(parents=True, exist_ok=True)
    manifest = dict(kind="exploratory_diagnostic_not_holdout_validation", environment=environment(),
                    time_stride=args.time_stride, rows=len(rows), sensors=[0.05, 0.10, 0.15, 0.20, 0.25],
                    training_noise=0, training_seed=1, cached_time_alignment="inferred from legacy diag_library.py; depth and row counts checked",
                    sources=[fingerprint(ROOT / "intermediate/data/th.txt"), *map(fingerprint, paths), *map(fingerprint, metadata_paths)],
                    code=[fingerprint(p) for p in sorted((ROOT / "src/deepgs").glob("*.py"))] +
                         [fingerprint(Path(__file__)), fingerprint(ROOT / "benchmarks/common.py")],
                    hybrid_warning="Counterfactual diagnostic libraries need not be derivatives of a single field.")
    manifest_path = args.output / "manifest.json"
    if manifest_path.exists() and json.loads(manifest_path.read_text(encoding="utf-8")) != manifest:
        raise ValueError("Output provenance differs; choose a new output directory")
    save_json(manifest_path, manifest)

    def run(label, lib, sweep=False):
        path = args.output / f"{label}.json"
        if path.exists():
            print(f"cached {label}", flush=True)
            return
        record = dict(label=label, metrics=metrics(lib, fd), selections=selections(lib, sweep))
        save_json(path, record)
        print(label, [(s["selector"], s.get("normalization"), s.get("value", s["lam"]), s["terms"]) for s in record["selections"]], flush=True)

    run("fd", fd, True)
    for name, path in zip(args.variants, paths):
        with np.load(path) as cache:
            if cache["theta"].shape != (21 * (len(full.times) - 1), 1):
                raise ValueError(f"Unexpected legacy cache shape: {path}")
            if "time" in cache:
                np.testing.assert_allclose(cache["time"][:, 0], np.tile(full.times[1:], 21), rtol=0, atol=1e-12)
            lib = subset(CandidateLibrary(cache["theta"], cache["terms"], cache["theta_t"], term_names(4), cache["depth"]), rows)
        np.testing.assert_allclose(lib.depth, fd.depth, rtol=0, atol=1e-12)
        run(name, lib, True)
        if not args.no_hybrids:
            run(name + "_fd_theta", CandidateLibrary(fd.theta, lib.terms, lib.theta_t, lib.names, lib.depth))
            run(name + "_fd_time", CandidateLibrary(lib.theta, lib.terms, fd.theta_t, lib.names, lib.depth))
            run(name + "_fd_space", CandidateLibrary(lib.theta, fd.terms, lib.theta_t, lib.names, lib.depth))
            run(name + "_fd_derivatives", CandidateLibrary(lib.theta, fd.terms, fd.theta_t, lib.names, lib.depth))


if __name__ == "__main__":
    main()
